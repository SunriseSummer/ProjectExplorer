export function getPresets(node) {
  if (!node || node.path === '') return ROOT_PROMPTS;
  return node.type === 'dir' ? DIR_PROMPTS : FILE_PROMPTS;
}

export function resolvePrompt(template, node) {
  return template.replace(/\{path\}/g, node ? node.path || '' : '');
}
