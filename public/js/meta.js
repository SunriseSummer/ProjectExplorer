export function kindMeta(kind) {
  return KIND[kind] || KIND.file;
}

export function kindOf(node) {
  if (node.type === 'dir') return node.path === '' ? 'module' : 'dir';
  return EXT_KIND[node.ext] || EXT_KIND[node.name] || 'file';
}
